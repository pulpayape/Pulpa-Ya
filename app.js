        function handleLogoUpload(event) {
            const file = event.target.files[0];
            if (file) {
                const reader = new FileReader();
                reader.onload = function(e) {
                    cmsState.logoUrl = e.target.result;
                    const customImg = document.getElementById('custom-logo-img');
                    const defaultSvg = document.getElementById('default-logo-svg');
                    if (customImg && defaultSvg) {
                        customImg.src = cmsState.logoUrl;
                        customImg.classList.remove('hidden');
                        defaultSvg.classList.add('hidden');
                    }
                    saveCMSState();
                    openNotification("Logo actualizado correctamente.");
                };
                reader.readAsDataURL(file);
            }
        }

