        let _heroTimer = null;
        function renderHeroImages() {
            const container = document.getElementById('hero-images-container');
            const defaultImg = document.getElementById('hero-default-image');

            clearInterval(_heroTimer);
            _heroTimer = null;
            container.classList.remove('hs-rotate', 'hs-fade', 'hs-slide', 'hs-up', 'hs-zoom', 'hs-flip', 'hs-blur');
            container.querySelectorAll('.hs-item, .dynamic-hero-img').forEach(el => el.remove());

            if (!cmsState.heroImages || cmsState.heroImages.length === 0) {
                if (defaultImg) defaultImg.classList.remove('hidden');
                return;
            }
            if (defaultImg) defaultImg.classList.add('hidden');

            const cfg = Object.assign({ mode: 'rotate', effect: 'fade', interval: 4, speed: 800 }, cmsState.heroSlide || {});
            const rotate = cfg.mode === 'rotate' && cmsState.heroImages.length > 1;

            cmsState.heroImages.forEach((imgObj) => {
                const imgEl = document.createElement('picture');
                imgEl.className = "dynamic-hero-img drop-shadow-2xl transition-all duration-300 transform hover:scale-105 inline-block m-2";
                imgEl.innerHTML = `
                    <source media="(max-width: 640px)" srcset="${imgObj.mobileUrl || imgObj.desktopUrl}">
                    <img src="${imgObj.desktopUrl}" alt="Hero Image" style="width: ${imgObj.sizePx}px; height: auto;" class="rounded-3xl object-contain mx-auto">
                `;
                if (rotate) {
                    const wrap = document.createElement('div');
                    wrap.className = 'hs-item';
                    wrap.appendChild(imgEl);
                    container.appendChild(wrap);
                } else {
                    container.appendChild(imgEl);
                }
            });

            if (!rotate) return;
            container.classList.add('hs-rotate', 'hs-' + cfg.effect);
            container.style.setProperty('--hs-speed', (Number(cfg.speed) || 800) + 'ms');
            const items = Array.from(container.querySelectorAll('.hs-item'));
            let current = 0;
            const show = (i, prev) => items.forEach((el, k) => {
                el.classList.toggle('hs-off', k !== i);
                el.classList.toggle('hs-prev', k === prev);
                el.classList.toggle('hs-next', k !== prev);
            });
            show(0, -1);
            _heroTimer = setInterval(() => {
                const prev = current;
                current = (current + 1) % items.length;
                show(current, prev);
            }, Math.max(1, Number(cfg.interval) || 4) * 1000);
        }

