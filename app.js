function updateSEO() {
    try {
        const strip = s => String(s || '').replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
        const isUrl = s => /^https?:\/\//i.test(String(s || ''));
        const site = SITE_URL + '/';
        const brand = strip(cmsState.brandName).replace(/\.+$/, '') || 'Pulpa Ya';

        const org = { '@type': 'Organization', '@id': site + '#org', name: brand, url: site };
        if (isUrl(cmsState.logoUrl)) org.logo = cmsState.logoUrl;
        const same = (cmsState.socials || []).map(s => s && s.url ? normalizeSocialUrl(s.url) : '').filter(u => isUrl(u));
        if (same.length) org.sameAs = same;

        const graph = [
            org,
            { '@type': 'WebSite', '@id': site + '#web', url: site, name: brand, inLanguage: 'es', publisher: { '@id': site + '#org' } }
        ];

        const items = (cmsState.productos || []).filter(p => p && p.name && !p.hidden).map((p, i) => {
            const prod = { '@type': 'Product', name: strip(p.name), description: strip(p.desc) || strip(p.rinde) || strip(p.name) };
            const img = (p.images || []).find(isUrl);
            if (img) prod.image = img;
            if (p.sku) prod.sku = String(p.sku);
            if (p.showPrice !== false && Number(p.price) > 0) {
                prod.offers = { '@type': 'Offer', price: Number(p.price).toFixed(2), priceCurrency: 'PEN',
                                availability: 'https://schema.org/InStock', url: site + '#productos' };
            }
            return { '@type': 'ListItem', position: i + 1, item: prod };
        });
        if (items.length) graph.push({ '@type': 'ItemList', name: 'Productos de ' + brand, itemListElement: items });

        let tag = document.getElementById('ld-main');
        if (!tag) { tag = document.createElement('script'); tag.type = 'application/ld+json'; tag.id = 'ld-main'; document.head.appendChild(tag); }
        tag.textContent = JSON.stringify({ '@context': 'https://schema.org', '@graph': graph });
    } catch (e) {}
}

async function loadPublicConfig() {
    if (IS_GAS) return;                                   // dentro de Apps Script se usa el código original
    const safety = setTimeout(_revealPage, 3500);         // nunca dejes la página oculta
    // a) config.json (está en tu repositorio, carga al instante)
    try {
        const r = await fetch('config.json', { cache: 'no-cache' });
        if (r.ok) _applyPublicConfig(await r.json());
    } catch (e) {}
    updateSEO();
    _revealPage();
    clearTimeout(safety);
    // b) configuración más reciente desde Apps Script (si cambiaste algo y aún no actualizas config.json)
    if (/^https:\/\/script\.google\.com\//.test(API_URL)) {
        try {
            const r = await fetch(API_URL + (API_URL.indexOf('?') === -1 ? '?' : '&') + 'api=config', { redirect: 'follow' });
            if (r.ok) _applyPublicConfig(await r.text());
        } catch (e) {}
    }
}

window.addEventListener('DOMContentLoaded', loadPublicConfig);
