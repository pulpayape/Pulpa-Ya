        const _webpSupported = document.createElement('canvas').toDataURL('image/webp').startsWith('data:image/webp');

        // Resize + compress so many photos fit in the browser storage
        function compressImage(file, maxSize = 900) {
            return new Promise((resolve, reject) => {
                const reader = new FileReader();
                reader.onerror = () => reject(new Error('read'));
                reader.onload = (e) => {
                    const img = new Image();
                    img.onerror = () => reject(new Error('image'));
                    img.onload = () => {
                        if (!img.width || !img.height) return reject(new Error('size'));
                        const scale = Math.min(1, maxSize / Math.max(img.width, img.height));
                        const w = Math.round(img.width * scale);
                        const h = Math.round(img.height * scale);
                        const canvas = document.createElement('canvas');
                        canvas.width = w;
                        canvas.height = h;
                        const ctx = canvas.getContext('2d');
                        if (!_webpSupported) { ctx.fillStyle = '#ffffff'; ctx.fillRect(0, 0, w, h); }
                        ctx.drawImage(img, 0, 0, w, h);
                        resolve(_webpSupported ? canvas.toDataURL('image/webp', 0.85) : canvas.toDataURL('image/jpeg', 0.85));
                    };
                    img.src = e.target.result;
                };
                reader.readAsDataURL(file);
            });
        }

