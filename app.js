        const IS_GAS = (typeof google !== 'undefined' && google.script && google.script.run) ? true : false;
        let _remoteTimer = null, _pwdWarned = false;

        let _remoteReady = false, _pushing = false, _pushAgain = false;

        function queueRemoteSave() {
            if (!IS_GAS) return;
            clearTimeout(_remoteTimer);
            _remoteTimer = setTimeout(pushRemoteConfig, 1500);
        }

        // Busca imágenes nuevas (data:image...) dentro de la configuración para subirlas a Drive
        function _collectDataImages(node, out) {
            if (!node || typeof node !== 'object') return;
            Object.keys(node).forEach(k => {
                const v = node[k];
                if (typeof v === 'string') {
                    if (v.indexOf('data:image/') === 0) out.push([node, k, v]);
                } else if (v && typeof v === 'object') {
                    _collectDataImages(v, out);
                }
            });
        }

        function _runServer(fn, args) {
            return new Promise((resolve, reject) => {
                google.script.run
                    .withSuccessHandler(resolve)
                    .withFailureHandler(err => reject(new Error((err && err.message) || String(err))))
                [fn](...args);
            });
        }

        async function pushRemoteConfig(manual) {
            if (!IS_GAS) return;
            const inp = document.getElementById('admin-pwd');
            const pwd = inp ? inp.value : '';
            const adminOpen = !document.getElementById('admin-modal').classList.contains('hidden');
            if (!_remoteReady) {
                // Aún no se leyó lo guardado en el servidor: no se sobrescribe nada.
                if (manual === true) openNotification("Espera unos segundos: se está cargando la configuración guardada.");
                return;
            }
            if (!pwd) {
                if (manual === true || (adminOpen && !_pwdWarned)) {
                    _pwdWarned = true;
                    openNotification("Escribe la contraseña arriba (Panel CMS) y pulsa Publicar para guardar en el servidor.");
                }
                return;
            }
            if (_pushing) { _pushAgain = true; return; }
            _pushing = true;
            try {
                // 1) Imágenes nuevas -> carpeta de Drive (se reemplazan por su enlace)
                for (let round = 0; round < 5; round++) {
                    const found = [];
                    _collectDataImages(cmsState, found);
                    if (!found.length) break;
                    openNotification("Subiendo " + found.length + " imagen(es) a Drive...");
                    const done = {};
                    for (const [node, key, val] of found) {
                        if (!done[val]) {
                            const r = await _runServer('uploadImage', [val, 'imagen', pwd]);
                            if (!r || !r.ok) throw new Error((r && r.error) || 'No se pudo subir la imagen.');
                            done[val] = r.url;
                        }
                        if (node[key] === val) node[key] = done[val];
                    }
                    try { localStorage.setItem('fresco_cms_state', JSON.stringify(cmsState)); } catch (e) {}
                }
                // 2) Configuración -> hoja de Google Sheets
                const res = await _runServer('saveCMSConfig', [JSON.stringify(cmsState), pwd]);
                if (res && res.ok) openNotification("Cambios publicados ✓");
                else openNotification((res && res.error) || "No se pudo guardar.");
            } catch (err) {
                openNotification("No se pudo guardar en el servidor: " + ((err && err.message) || err));
            } finally {
                _pushing = false;
                if (_pushAgain) { _pushAgain = false; queueRemoteSave(); }
            }
        }

